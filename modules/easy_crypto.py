def _bytes(value):
    return value.encode('ascii') if isinstance(value, str) else bytes(value)


def xor_encrypt_data_bytes(idx, data_bytes):
    idx &= ENCRYPT_KEY_IDX_MASK
    idx2 = idx + ENCRYPT_KEY2_IDX
    output = bytearray()
    for value in _bytes(data_bytes):
        output.append(value ^ ENCRYPT_KEY_XOR[idx] ^ ENCRYPT_KEY_XOR[idx2])
        idx = (idx + 1) & ENCRYPT_KEY_IDX_MASK
        idx2 += 1
        if idx2 >= ENCRYPT_KEY2_MAX:
            idx2 = ENCRYPT_KEY2_IDX
    return bytes(output)


